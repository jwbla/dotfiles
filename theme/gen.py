def emit_reference_css(T: Theme) -> tuple[str, str]:
    """theme/neu.css -- every token as literal CSS, for eyeballing against the DS."""
    f = T.flat()
    t = T.t
    L = [f"/* {STAMP} */",
         "/* The resolved dark theme, flattened (no color-mix/oklch left to evaluate).",
         "   Diff this against ~/dev/rgtv-ds/src/theme/variables.css to see drift. */",
         "", ":root {"]
    for k in ("bg", "bgComponent", "bgCard", "hoverHighlight", "shadowDark", "shadowLight",
              "text", "textMuted", "textDim"):
        L.append(f"  --neu-{re.sub(r'(?<!^)(?=[A-Z])', '-', k).lower()}: {f[k]};")
    L.append(f"  --neu-accent: {f['accent']};")
    L.append(f"  --neu-accent-text: {f['primary']};")
    L.append(f"  --neu-accent-secondary: {f['accentSecondary']};")
    L.append(f"  --neu-accent-secondary-text: {f['secondary']};")
    L.append(f"  --neu-accent-tertiary: {f['accentTertiary']};")
    L.append(f"  --neu-accent-tertiary-text: {f['tertiary']};")
    for n in T.status:
        L.append(f"  --neu-{n}: {f[n + 'Glow']};")
        L.append(f"  --neu-{n}-text: {f[n]};")
    for base in ("accent", "secondary", "tertiary"):
        for step in t["shadeSteps"]:
            nm = "accent" if base == "accent" else f"accent-{base}"
            L.append(f"  --neu-{nm}-{step}: {f[f'{base}_{step}']};")
    for k, s in t["shadow"].items():
        if k.startswith("_"):
            continue
        o, b = s["offset"], s["blur"]
        L.append(f"  --neu-shadow-{k}: {o}px {o}px {b}px {f['shadowDark']}, "
                 f"-{o}px -{o}px {b}px {f['shadowLight']};")
        L.append(f"  --neu-shadow-{k}-gap: {s['gap']}px;")
    for k, s in t["shadowInset"].items():
        o, b = s["offset"], s["blur"]
        L.append(f"  --neu-shadow-inset-{k}: inset {o}px {o}px {b}px {f['shadowDark']}, "
                 f"inset -{o}px -{o}px {b}px {f['shadowLight']};")
    L.append(f"  --neu-focus-shadow: 0 0 0 {t['focusRing']}px {f['accent']};")
    L.append(f"  --neu-border-hairline-color: {f['hairline']};")
    for k, n in t["size"].items():
        L.append(f"  --neu-size-{k}: {n}px;")
    for k, n in t["radius"].items():
        L.append(f"  --neu-radius-{k}: {n}px;")
    for k, v in t["type"]["rem"].items():
        L.append(f"  --neu-font-{k}: {v}rem; /* {T.px(k)}px */")
    L.append(f"  --neu-transition-fast: {t['motion']['fastMs'] / 1000}s;")
    L.append(f"  --neu-transition-base: {t['motion']['baseMs'] / 1000}s;")
    L.append(f"  --neu-transition: {t['motion']['defaultMs'] / 1000}s;")
    L.append(f"  --neu-scrollbar-thumb: {f['scrollThumb']};")
    L.append("}")
    return "theme/neu.css", "\n".join(L) + "\n"


def ansi_palette(T: Theme) -> list[tuple[str, tuple]]:
    """The 16 ANSI slots.

    Greys 0/7/8/15 come from the neu surface ramp, so a terminal sits on the
    same ground as the shell. red/green/yellow/blue stay Catppuccin because the
    DS keeps its *status* hues Catppuccin. magenta/cyan take the brand secondary
    and tertiary -- they aren't status colours, so they're where the brand lands.
    """
    c = T.ctp
    s = T.surf
    return [
        ("black", s["hoverHighlight"]), ("red", c["red"]), ("green", c["green"]),
        ("yellow", c["yellow"]), ("blue", c["blue"]), ("magenta", T.secondary),
        ("cyan", T.tertiary), ("white", s["text"]),
        ("brblack", s["shadowLight"]), ("brred", shade(c["red"], 15)),
        ("brgreen", shade(c["green"], 15)), ("bryellow", shade(c["yellow"], 15)),
        ("brblue", shade(c["blue"], 15)), ("brmagenta", shade(T.secondary, 15)),
        ("brcyan", shade(T.tertiary, 15)), ("brwhite", (1.0, 1.0, 1.0, 1.0)),
    ]


