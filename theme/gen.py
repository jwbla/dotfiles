ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = ROOT / "theme" / "tokens.json"
TEMPLATES = ROOT / "theme" / "templates"

STAMP = "generated by theme/gen.py from theme/tokens.json; do not edit"


# ---------------------------------------------------------------- colour ----

def parse(h: str) -> tuple[float, float, float, float]:
    h = h.lstrip("#")
    if len(h) == 6:
        r, g, b, a = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255
    elif len(h) == 8:
        r, g, b, a = (int(h[i:i + 2], 16) for i in (0, 2, 4, 6))
    else:
        raise ValueError(f"bad hex {h!r}")
    return r / 255, g / 255, b / 255, a / 255


def hexa(c: tuple[float, float, float, float]) -> str:
    r, g, b, a = c
    out = "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, b))
    if a < 1:
        out += "%02x" % max(0, min(255, round(a * 255)))
    return out


def rgb6(c) -> str:
    """Drop alpha entirely -- for formats with no alpha channel."""
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in c[:3])


def alpha(c, a: float):
    return (c[0], c[1], c[2], a)


def over(c, bg):
    """Composite c over opaque bg."""
    a = c[3]
    return tuple(c[i] * a + bg[i] * (1 - a) for i in range(3)) + (1.0,)


def mix_srgb(a, b, p: float):
    """`color-mix(in srgb, a p%, b)` -- gamma-encoded lerp, p in 0..100."""
    t = p / 100
    return tuple(a[i] * t + b[i] * (1 - t) for i in range(3)) + (a[3] * t + b[3] * (1 - t),)


# --- OKLab / OKLCh (Bjorn Ottosson's matrices, same path the browser takes) ---

def _lin(u):
    return u / 12.92 if u <= 0.04045 else ((u + 0.055) / 1.055) ** 2.4


def _unlin(u):
    return 12.92 * u if u <= 0.0031308 else 1.055 * (u ** (1 / 2.4)) - 0.055


def to_oklab(c):
    r, g, b = (_lin(v) for v in c[:3])
    l = 0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b
    m = 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b
    s = 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b
    l_, m_, s_ = (v ** (1 / 3) if v > 0 else -((-v) ** (1 / 3)) for v in (l, m, s))
    return (
        0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_,
        1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_,
        0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_,
    )


def from_oklab(lab, a=1.0):
    L, A, B = lab
    l_ = L + 0.3963377774 * A + 0.2158037573 * B
    m_ = L - 0.1055613458 * A - 0.0638541728 * B
    s_ = L - 0.0894841775 * A - 1.2914855480 * B
    l, m, s = (v ** 3 for v in (l_, m_, s_))
    r = +4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    b = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    return tuple(min(1.0, max(0.0, _unlin(v))) for v in (r, g, b)) + (a,)


def shade(c, pct: int):
    """color-mix(in oklch, c, white|black |pct|%) -- positive lightens.

    White and black are chroma-zero, so their hue is powerless: only L and C
    move, the hue is carried through unchanged. That is exactly why the DS
    mixes in OKLCh -- sRGB would wash the hue toward grey.
    """
    t = abs(pct) / 100
    L, A, B = to_oklab(c)
    C = math.hypot(A, B)
    H = math.atan2(B, A)
    L = L * (1 - t) + (1.0 if pct > 0 else 0.0) * t
    C = C * (1 - t)
    return from_oklab((L, C * math.cos(H), C * math.sin(H)), c[3])


# --- contrast, ported from src/contrast.ts + onAccent() in src/themes.ts ------

INK_LIGHT, INK_DARK = "#cdd6f4", "#11111b"
INK_LIGHT_MAX, INK_DARK_MAX = "#ffffff", "#000000"
AA_NORMAL = 4.5


def luminance(c) -> float:
    r, g, b = (_lin(v) for v in c[:3])
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b) -> float:
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def on_accent(face) -> str:
    """Readable ink for text sitting on `face`.

    Splits at the luminance where white and black contrast equally
    (sqrt(1.05 * 0.05) - 0.05), then escalates to a pure endpoint if the themed
    ink can't clear AA for normal text -- exactly what themes.ts does, which is
    why #8b2fe0 ends up with pure white rather than the themed #cdd6f4.
    """
    split = math.sqrt(1.05 * 0.05) - 0.05
    themed, maxed = ((INK_DARK, INK_DARK_MAX) if luminance(face) > split
                     else (INK_LIGHT, INK_LIGHT_MAX))
    return themed if contrast(parse(themed), face) >= AA_NORMAL else maxed


# ------------------------------------------------------------- resolution ----

class Theme:
    """Every token, resolved to concrete colours and numbers."""

    def __init__(self, t: dict):
        self.t = t
        self.ctp = {k: parse(v) for k, v in t["ctp"].items()}
        self.brand = {k: parse(v) for k, v in t["brand"].items()}
        self.surf = {k: parse(v) for k, v in t["surface"].items()}
        self.domain = {k: parse(v) for k, v in t["domain"].items()}

        self.bg = self.surf["bg"]
        self.primary = self.brand["primary"]
        self.secondary = self.brand["secondary"]
        self.tertiary = self.brand["tertiary"]

        # Translucent "glow" halves of each semantic pair.
        g = t["accentGlow"] / 100
        self.accent = alpha(self.primary, g)
        self.accentSecondary = alpha(self.secondary, g)
        self.accentTertiary = alpha(self.tertiary, g)

        self.status = {}
        for name, spec in t["status"].items():
            hue = self.ctp[spec["hue"]]
            self.status[name] = {"text": hue, "glow": alpha(hue, spec["glow"] / 100)}

        self.hairline = alpha(self.surf["textDim"], t["hairlineMix"] / 100)
        self.scrollThumb = mix_srgb(self.primary, self.surf["bgComponent"],
                                    t["scrollbar"]["thumbMix"])

    # -- helpers used by emitters -------------------------------------------

    def px(self, rem_key: str) -> int:
        return round(self.t["type"]["rem"][rem_key] * self.t["type"]["rootPx"])

    def ramp(self, base):
        return {k: shade(base, v) for k, v in self.t["shadeSteps"].items()}

    def flat(self) -> dict[str, str]:
        """Flat `{{name}}` namespace for templates. Values are CSS hex."""
        v: dict[str, str] = {}
        for k, c in self.ctp.items():
            v[f"ctp_{k}"] = hexa(c)
        for k, c in self.brand.items():
            v[k] = hexa(c)
        for k, c in self.surf.items():
            v[k] = hexa(c)
        v["accent"] = hexa(self.accent)
        v["accentSecondary"] = hexa(self.accentSecondary)
        v["accentTertiary"] = hexa(self.accentTertiary)
        v["hairline"] = hexa(self.hairline)
        v["scrollThumb"] = hexa(self.scrollThumb)
        for name, pair in self.status.items():
            v[name] = hexa(pair["text"])
            v[f"{name}Glow"] = hexa(pair["glow"])
        for name, base in (("accent", self.primary), ("secondary", self.secondary),
                           ("tertiary", self.tertiary)):
            for step, c in self.ramp(base).items():
                v[f"{name}_{step}"] = hexa(c)
        # opaque composites, for formats with no alpha
        v["accentOnBg"] = rgb6(over(self.accent, self.bg))
        v["hairlineOnBg"] = rgb6(over(self.hairline, self.surf["bgComponent"]))

        # Hyprland wants rgba(rrggbbaa) with no '#'
        for k in list(v):
            h = v[k].lstrip("#")
            v[f"hl_{k}"] = "rgba(%s)" % (h if len(h) == 8 else h + "ff")
        # QML/Qt want #aarrggbb
        for k in [k for k in v if not k.startswith("hl_")]:
            h = v[k].lstrip("#")
            v[f"qt_{k}"] = "#" + (h[6:8] + h[0:6] if len(h) == 8 else h)

        for k, n in self.t["size"].items():
            v[f"size_{k}"] = str(n)
        for k, n in self.t["radius"].items():
            v[f"radius_{k}"] = str(n)
        for k, n in self.t["border"].items():
            v[f"border_{k}"] = str(n)
        for k in self.t["type"]["rem"]:
            v[f"font_{k}"] = str(self.px(k))
        for k, n in self.t["type"]["weight"].items():
            v[f"weight_{k}"] = str(n)
        for k, n in self.t["motion"].items():
            v[k] = str(n)
        for k, n in self.t["type"]["font"].items():
            if not k.startswith("_"):
                v[f"family_{k}"] = n
        for k, n in self.t["desktop"].items():
            if isinstance(n, (int, float, str)) and not k.startswith("_"):
                v[f"desktop_{k}"] = str(n)
        d = self.t["desktop"]
        v["barHeight"] = str(d["barHeight"])
        v["barHeightPlusGap"] = str(d["barHeight"] + self.t["shadow"]["l"]["gap"])
        v["dockIconPx"] = str(d["dockIconPx"])
        v["user_name"] = self.t["desktop"]["user"]["name"]
        v["user_initials"] = self.t["desktop"]["user"]["initials"]
        v["wall_w"] = str(self.t["desktop"]["wallpaper"]["width"])
        v["wall_h"] = str(self.t["desktop"]["wallpaper"]["height"])
        v["wall_bloom"] = "1" if self.t["desktop"]["wallpaper"].get("style") == "bloom" else "0"
        v["focusRing"] = str(self.t["focusRing"])
        for k, sh in self.t["shadow"].items():
            if k.startswith("_"):
                continue
            v[f"shadow_{k}_offset"] = str(sh["offset"])
            v[f"shadow_{k}_blur"] = str(sh["blur"])
            v[f"shadow_{k}_gap"] = str(sh["gap"])
        for k in ("primary", "secondary", "tertiary"):
            v[f"ink_{k}"] = on_accent(getattr(self, k))
        for k, pair in self.status.items():
            v[f"ink_{k}"] = on_accent(pair["text"])
        for base in ("accent", "secondary", "tertiary"):
            for step, c in self.ramp(getattr(self, {"accent": "primary"}.get(base, base))).items():
                v[f"ink_{base}_{step}"] = on_accent(c)
        v["stamp"] = STAMP
        v["repo_root"] = str(ROOT)
        v["home"] = str(pathlib.Path.home())
        # hyprlock/hyprland animation speeds are in ds (1 = 100ms)
        for k in ("fast", "base", "default", "slow"):
            v[f"motion_{k}_ds"] = str(max(1, round(self.t["motion"][k + "Ms"] / 100)))
        return v


# ------------------------------------------------------------- templating ----

PLACEHOLDER = re.compile(r"\{\{([a-zA-Z0-9_]+)\}\}")


def render(name: str, flat: dict[str, str]) -> str:
    src = (TEMPLATES / name).read_text()
    missing: list[str] = []

    def sub(m):
        key = m.group(1)
        # {{u_e0b6}} -> the literal character. Nerd-font glyphs live in the BMP
        # private-use area and do not survive being written directly, so every
        # icon in a template is spelled by codepoint and materialised here.
        if re.fullmatch(r"u_[0-9a-fA-F]{4,6}", key):
            return chr(int(key[2:], 16))
        if key not in flat:
            missing.append(key)
            return m.group(0)
        return flat[key]

    out = PLACEHOLDER.sub(sub, src)
    if missing:
        raise SystemExit(f"{name}: unknown placeholder(s): {sorted(set(missing))}")
    return out


