def emit_qt6ct(T: Theme) -> tuple[str, str]:
    """A qt6ct/qt5ct colour scheme: 3 states x 21 roles of #aarrggbb."""
    f, s = T.flat(), T.surf
    q = lambda c: "#ff" + rgb6(c).lstrip("#")  # noqa: E731
    win, base, txt = s["bg"], s["bgComponent"], s["text"]
    dis = s["textDim"]
    roles = {
        "WindowText": txt, "Button": s["bgComponent"], "Light": s["shadowLight"],
        "Midlight": s["hoverHighlight"], "Dark": s["shadowDark"], "Mid": s["hoverHighlight"],
        "Text": txt, "BrightText": (1.0, 1.0, 1.0, 1.0), "ButtonText": txt,
        "Base": base, "Window": win, "Shadow": s["shadowDark"],
        "Highlight": T.primary, "HighlightedText": (1.0, 1.0, 1.0, 1.0),
        "Link": T.tertiary, "LinkVisited": T.secondary,
        "AlternateBase": s["bgCard"], "NoRole": win,
        "ToolTipBase": s["bgCard"], "ToolTipText": txt, "PlaceholderText": s["textMuted"],
    }
    order = ["WindowText", "Button", "Light", "Midlight", "Dark", "Mid", "Text",
             "BrightText", "ButtonText", "Base", "Window", "Shadow", "Highlight",
             "HighlightedText", "Link", "LinkVisited", "AlternateBase", "NoRole",
             "ToolTipBase", "ToolTipText", "PlaceholderText"]
    active = ", ".join(q(roles[r]) for r in order)
    disabled = ", ".join(q(dis if r in ("WindowText", "Text", "ButtonText",
                                        "PlaceholderText") else roles[r]) for r in order)
    return "qt6ct/neu.conf", (
        f"# {STAMP}\n[ColorScheme]\n"
        f"active_colors={active}\n"
        f"disabled_colors={disabled}\n"
        f"inactive_colors={active}\n")


def emit_shell_colors(T: Theme) -> tuple[str, str]:
    """bin/neu-colors.sh -- truecolor escapes for _motd and sysinfo.sh."""
    f, s = T.flat(), T.surf
    def esc(c):
        r, g, b = (round(v * 255) for v in c[:3])
        return f"\\033[38;2;{r};{g};{b}m"
    pairs = [("NEU_ACCENT", T.primary), ("NEU_ACCENT2", T.secondary),
             ("NEU_ACCENT3", T.tertiary), ("NEU_TEXT", s["text"]),
             ("NEU_MUTED", s["textMuted"]), ("NEU_DIM", s["textDim"]),
             ("NEU_SUCCESS", T.status["success"]["text"]),
             ("NEU_ERROR", T.status["error"]["text"]),
             ("NEU_WARNING", T.status["warning"]["text"]),
             ("NEU_INFO", T.status["info"]["text"])]
    L = [f"# {STAMP}",
         "# ANSI truecolor escapes. `source` this; use with printf/echo -e.", ""]
    for name, c in pairs:
        L.append(f"{name}='{esc(c)}'   # {rgb6(c)}")
    L.append("NEU_RESET='\\033[0m'")
    return "bin/neu-colors.sh", "\n".join(L) + "\n"


