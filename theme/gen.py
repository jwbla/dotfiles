def rasterize(T: Theme) -> list[str]:
    """SVG -> PNG. rsvg-convert is present on this box; Pillow is not."""
    import shutil
    import subprocess
    exe = shutil.which("rsvg-convert")
    if not exe:
        print("  !  rsvg-convert missing; skipping rasters", file=sys.stderr)
        return []
    w = T.t["desktop"]["wallpaper"]["width"]
    h = T.t["desktop"]["wallpaper"]["height"]
    jobs = [("theme/wall/neu.svg", f"theme/wall/neu-{w}x{h}.png", w, h),
            ("theme/wall/neu-avatar.svg", "theme/wall/neu-avatar.png", 256, 256)]
    done = []
    for src, dst, w_, h_ in jobs:
        s_, d_ = ROOT / src, ROOT / dst
        if not s_.exists():
            continue
        subprocess.run([exe, "-w", str(w_), "-h", str(h_), "-o", str(d_), str(s_)],
                       check=True)
        done.append(dst)
    return done


def scan_literal_glyphs() -> list[str]:
    """Any literal BMP private-use character that reached a QML file is a bug.

    Nerd-font glyphs in U+E000-F8FF get silently dropped between an editor and
    the disk, leaving an empty string that looks fine in a diff. Everything must
    go through Icons.qml (generated) or a \\uXXXX escape.
    """
    bad = []
    for f in sorted((ROOT / "quickshell").rglob("*.qml")):
        for i, line in enumerate(f.read_text().splitlines(), 1):
            for c in line:
                if 0xE000 <= ord(c) <= 0xF8FF:
                    bad.append(f"{f.relative_to(ROOT)}:{i}: literal U+{ord(c):04X}")
    return bad


def main(argv: list[str]) -> int:
    check = "--check" in argv
    listing = "--list" in argv
    T = Theme(json.loads(TOKENS.read_text()))
    out = build(T)

    if listing:
        for p in sorted(out):
            print(p)
        return 0

    drift = []
    for rel, body in sorted(out.items()):
        dest = ROOT / rel
        current = dest.read_text() if dest.exists() else None
        if current == body:
            continue
        if check:
            drift.append(rel)
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(body)
        print(f"  {'+' if current is None else 'M'} {rel}")

    glyphs = scan_literal_glyphs()
    if glyphs and check:
        print("literal private-use glyphs found (use Icons.qml or a \\uXXXX escape):",
              file=sys.stderr)
        for g in glyphs:
            print(f"  {g}", file=sys.stderr)

    if check:
        if drift:
            print("out of date (run `python3 theme/gen.py`):", file=sys.stderr)
            for d in drift:
                print(f"  {d}", file=sys.stderr)
        if drift or glyphs:
            return 1
        print("all generated files match theme/tokens.json; no literal glyphs on disk")
        return 0

    for png in rasterize(T):
        print(f"  M {png}")
    return 0



def qml_escape(cp: str) -> str:
    """Codepoint hex -> a QML/JS string escape (surrogate pair above the BMP)."""
    n = int(cp, 16)
    if n <= 0xFFFF:
        return "\\u%04x" % n
    v = n - 0x10000
    return "\\u%04x\\u%04x" % (0xD800 + (v >> 10), 0xDC00 + (v & 0x3FF))


def emit_icons_qml(T: Theme) -> tuple[str, str]:
    """quickshell/Icons.qml -- every nerd glyph, by codepoint.

    Literal private-use characters get silently dropped somewhere between an
    editor and the disk (it has already happened once in this repo: the timew
    segment's symbol was an empty string). Generating them from hex means a glyph
    can never go missing without theme/tokens.json changing.
    """
    ic = T.t["icons"]
    L = ["pragma Singleton", "", "import QtQuick", "import Quickshell", "",
         f"// {STAMP}", "//",
         "// Nerd-font glyphs, written as escapes rather than literal characters.",
         "// Every codepoint here is verified present in UbuntuMono Nerd Font.",
         "Singleton {"]
    for k, v in ic.items():
        if k.startswith("_"):
            continue
        if isinstance(v, list):
            items = ", ".join(f'"{qml_escape(c)}"' for c in v)
            L.append(f"    readonly property var {k}: [{items}]")
        else:
            L.append(f'    readonly property string {k}: "{qml_escape(v)}"')
    L.append("")
    L.append("    /** Pick from a low->high ramp by a 0..1 fraction. */")
    L.append("    function ramp(list, frac) {")
    L.append("        if (!list || list.length === 0) return \"\";")
    L.append("        const i = Math.round(Math.max(0, Math.min(1, frac)) * (list.length - 1));")
    L.append("        return list[i];")
    L.append("    }")
    L.append("}")
    return "quickshell/Icons.qml", "\n".join(L) + "\n"


