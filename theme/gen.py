#!/usr/bin/env python3
"""Export @rgtv/neu design tokens into every format this desktop speaks.

Single input:  theme/tokens.json
Outputs:       committed, generated files across the repo (see EMITTERS)

    python3 theme/gen.py           # write
    python3 theme/gen.py --check   # verify on-disk files match tokens (CI / pre-flight)
    python3 theme/gen.py --list    # show what would be written

Nothing here is hand-editable: change theme/tokens.json and re-run.

Colour maths mirrors the design system exactly --
  * shade ramps interpolate in OKLCh, like `color-mix(in oklch, ...)` in
    src/theme/variables.css and shade() in src/shade.ts
  * translucent "glow" tokens are `color-mix(in srgb, C n%, transparent)`,
    which in CSS keeps the hue and just sets alpha
  * two-colour srgb mixes lerp in gamma-encoded sRGB, as CSS does
"""

