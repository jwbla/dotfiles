def emit_theme_qml(T: Theme) -> tuple[str, str]:
    """quickshell/Theme.qml -- the shell's token singleton.

    Keeps every property name the pre-existing panes already bind to, so the
    shell keeps running the moment this is regenerated; the Catppuccin *greyscale*
    names (base/mantle/crust/surface*/overlay*/subtext*) are re-pointed at the neu
    ramp, while the *status* hues stay true Catppuccin, exactly as the DS does.
    """
    f = T.flat()
    q = lambda k: f["qt_" + k]  # noqa: E731
    t = T.t
    sh = t["shadow"]
    ins = t["shadowInset"]

    L = []
    a = L.append
    a("pragma Singleton\n")
    a("import QtQuick")
    a("import Quickshell\n")
    a(f"// {STAMP}")
    a("//")
    a("// @rgtv/neu v3.1.0 design tokens. Depth in this system comes from SHADOW,")
    a("// not surface contrast -- the three surface levels are only 4 values apart")
    a("// on purpose. Raised = pressable, inset = active/held, flat = disabled;")
    a("// see NeuSurface.qml, and don't break that grammar for decoration.")
    a("Singleton {")

    a("    // ---- surfaces -------------------------------------------------")
    for name, key in (("neuBg", "bg"), ("neuBgComponent", "bgComponent"),
                      ("neuBgCard", "bgCard"), ("neuHoverHighlight", "hoverHighlight"),
                      ("neuShadowDark", "shadowDark"), ("neuShadowLight", "shadowLight")):
        a(f'    readonly property color {name}: "{q(key)}"')

    a("\n    // ---- text -----------------------------------------------------")
    for name, key in (("neuText", "text"), ("neuTextMuted", "textMuted"),
                      ("neuTextDim", "textDim")):
        a(f'    readonly property color {name}: "{q(key)}"')
    a(f'    readonly property color neuHairline: "{q("hairline")}"')

    a("\n    // ---- brand ----------------------------------------------------")
    for name, key in (("neuAccentText", "primary"), ("neuAccent", "accent"),
                      ("neuAccentSecondaryText", "secondary"),
                      ("neuAccentSecondary", "accentSecondary"),
                      ("neuAccentTertiaryText", "tertiary"),
                      ("neuAccentTertiary", "accentTertiary")):
        a(f'    readonly property color {name}: "{q(key)}"')
    for base in ("accent", "secondary", "tertiary"):
        for step in t["shadeSteps"]:
            prop = "neu" + base.capitalize() + step.capitalize()
            a(f'    readonly property color {prop}: "{q(base + "_" + step)}"')

    a("\n    // ---- status (stays Catppuccin, as in the DS) -------------------")
    for name in T.status:
        a(f'    readonly property color neu{name.capitalize()}Text: "{q(name)}"')
        a(f'    readonly property color neu{name.capitalize()}: "{q(name + "Glow")}"')

    a("\n    // ---- categorical domain slots ---------------------------------")
    for k, c in T.domain.items():
        a(f'    readonly property color neuDomain{k}: "{rgb6(c)}"')

    a("\n    // ---- shadow ramp (offset / blur / reach) ----------------------")
    a("    // reach = offset + blur: space siblings by it so their shadows meet")
    a("    // rather than overlap. Straight from --neu-shadow-*-gap.")
    for k, s in sh.items():
        if k.startswith("_"):
            continue
        K = k.capitalize()
        a(f'    readonly property int shadow{K}Offset: {s["offset"]}')
        a(f'    readonly property int shadow{K}Blur: {s["blur"]}')
        a(f'    readonly property int shadow{K}Gap: {s["gap"]}')
    for k, s in ins.items():
        K = k.capitalize()
        a(f'    readonly property int inset{K}Offset: {s["offset"]}')
        a(f'    readonly property int inset{K}Blur: {s["blur"]}')

    a("\n    // ---- scale ----------------------------------------------------")
    for k, n in t["size"].items():
        a(f"    readonly property int size{k.capitalize()}: {n}")
    for k, n in t["radius"].items():
        a(f"    readonly property int radius{k.capitalize()}: {n}")
    for k, n in t["border"].items():
        a(f"    readonly property int border{k.capitalize()}: {n}")
    a(f'    readonly property int focusRing: {t["focusRing"]}')

    a("\n    // ---- type -----------------------------------------------------")
    a(f'    readonly property string fontFamily: "{t["type"]["font"]["shell"]}"')
    a(f'    readonly property string fontUi: "{t["type"]["font"]["ui"]}"')
    for k in t["type"]["rem"]:
        a(f"    readonly property int font{k.capitalize()}: {T.px(k)}")
    for k, n in t["type"]["weight"].items():
        a(f"    readonly property int weight{k.capitalize()}: {n}")
    for k, n in t["type"]["tracking"].items():
        if not k.startswith("_"):
            a(f"    readonly property real tracking{k.capitalize()}: {n}")

    a("\n    // ---- motion / z -----------------------------------------------")
    for k, n in t["motion"].items():
        a(f"    readonly property int {k}: {n}")
    for k, n in t["z"].items():
        a(f"    readonly property int z{k.capitalize()}: {n}")

    a("\n    // ---- desktop --------------------------------------------------")
    d = t["desktop"]
    a(f'    readonly property int barHeight: {d["barHeight"]}')
    a(f'    readonly property real barBlurAlpha: {d["barBlurAlpha"]}')
    a(f'    readonly property int dockIconPx: {d["dockIconPx"]}')
    a(f'    readonly property real dockMagHovered: {d["dockMagnify"]["hovered"]}')
    a(f'    readonly property real dockMagNeighbour: {d["dockMagnify"]["neighbour"]}')
    a(f'    readonly property int meterSegments: {d["meterSegments"]}')
    a(f'    readonly property string userName: "{d["user"]["name"]}"')
    a(f'    readonly property string userInitials: "{d["user"]["initials"]}"')

    a("\n    // ---- compatibility aliases ------------------------------------")
    a("    // The panes written before this port bind to Catppuccin names. The")
    a("    // greyscale ones now resolve to the neu ramp so nothing looks foreign;")
    a("    // the status hues are genuinely still Catppuccin.")
    alias = [
        ("base", "bg"), ("mantle", "bg"), ("crust", "shadowDark"),
        ("surface0", "bgComponent"), ("surface1", "hoverHighlight"),
        ("surface2", "shadowLight"),
        ("text", "text"), ("subtext1", "text"), ("subtext0", "textMuted"),
        ("overlay2", "textMuted"), ("overlay1", "textMuted"), ("overlay0", "textDim"),
        ("primary", "primary"), ("secondary", "secondary"),
        ("lightPrimary", "accent_light"), ("lightestPrimary", "accent_lighter"),
        ("darkPrimary", "accent_darker"),
        ("lightSecondary", "secondary_light"), ("lightestSecondary", "secondary_lighter"),
        ("darkSecondary", "secondary_darker"),
        # header colour: the DS paints the topbar title with the brand accent
        ("sapphire", "primary"),
    ]
    for name, key in alias:
        a(f'    readonly property color {name}: "{q(key)}"')
    for name in ("rosewater", "flamingo", "pink", "mauve", "red", "maroon", "peach",
                 "yellow", "green", "teal", "sky", "blue", "lavender"):
        a(f'    readonly property color {name}: "{rgb6(T.ctp[name])}"')

    a("\n    // Near-opaque on purpose. hyprland.lua asks for layer blur behind the")
    a("    // neu:* namespaces, but Hyprland 0.56.2 does not honour it, so without a")
    a("    // real backdrop a translucent panel just shows sharp text through itself.")
    a(f'    readonly property color panelBg: Qt.rgba(neuBgCard.r, neuBgCard.g, neuBgCard.b, {d["barBlurAlpha"]})')
    a("    readonly property color rowBg: neuBgComponent")
    a("    readonly property color rowHover: neuHoverHighlight")
    a(f'    readonly property int fontSize: {T.px("m")}')
    a(f'    readonly property int fontSizeSmall: {T.px("s")}')
    a(f'    readonly property int fontSizeHeader: {T.px("xl")}')
    a(f'    readonly property int padding: {t["size"]["m"]}')
    a(f'    readonly property int radius: {t["radius"]["m"]}')
    a("    readonly property int rowHeight: 30")
    a(f'    readonly property int animDuration: {t["motion"]["baseMs"]}')
    a("}")
    return "quickshell/Theme.qml", "\n".join(L) + "\n"


def emit_hypr_lua(T: Theme) -> tuple[str, str]:
    f = T.flat()
    t = T.t
    L = [f"-- {STAMP}", "--", "-- Colours and metrics for hyprland.lua. Hyprland wants rgba(rrggbbaa).", "",
         "return {"]
    for k in ("bg", "bgComponent", "bgCard", "shadowDark", "shadowLight",
              "text", "textMuted", "textDim", "primary", "secondary", "tertiary",
              "accent", "success", "error", "warning", "info"):
        L.append(f'    {k} = "{f["hl_" + k]}",')
    # Half-strength light for an unfocused window's shadow pair.
    # Half-strength dark for an unfocused window's shadow.
    dim = hexa(alpha(T.surf["shadowDark"], 0.55)).lstrip("#")
    L.append(f'    shadowDarkDim = "rgba({dim})",')
    L.append('    transparent = "rgba(00000000)",')
    L.append("")
    L.append(f'    rounding = {t["radius"]["m"]},')
    # Its own token, not focusRing: the animated brand border is a window
    # decoration, and thinning it should not also thin the shell's focus rings
    # or hyprlock's input outline.
    L.append(f'    border   = {t["desktop"]["windowBorder"]},')
    L.append(f'    gaps_in  = {t["shadow"]["l"]["gap"] // 2},')
    L.append(f'    gaps_out = {t["shadow"]["l"]["gap"]},')
    # Which rung of the shadow ramp a window wears. `l` matches the DS's
    # .neu-window, but a window is far larger than a card and the halo scales
    # with the surface it surrounds, so a lower tier reads truer at this size.
    wtier = t["shadow"][t["desktop"]["windowShadowTier"]]
    L.append(f'    shadow_range  = {wtier["blur"]},')
    L.append(f'    shadow_offset = {wtier["offset"]},')
    # Full reach of the raised pair (offset + blur) -- what a single
    # zero-offset gradient shadow needs to cover the same ground.
    L.append(f'    shadow_reach  = {t["shadow"]["l"]["gap"]},')
    L.append("")
    L.append("    -- Hyprland animation speed is in ds (1 = 100ms).")
    L.append(f'    speed_fast    = {round(t["motion"]["fastMs"] / 100)},')
    L.append(f'    speed_base    = {round(t["motion"]["baseMs"] / 100)},')
    L.append(f'    speed_default = {round(t["motion"]["defaultMs"] / 100)},')
    # Hyprland clamps animation speed to 100 ds (10s); the DS rainbow is 20s.
    L.append(f'    speed_rainbow = {min(100, round(t["motion"]["rainbowMs"] / 100))},')
    L.append("}")
    return "hypr/neu.lua", "\n".join(L) + "\n"


def emit_waybar_css(T: Theme) -> tuple[str, str]:
    f = T.flat()
    L = [f"/* {STAMP} */", "/* Fallback bar only -- the Quickshell bar is the real one. */", ""]
